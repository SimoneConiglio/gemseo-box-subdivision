"""The data profiles of the method's variants and of the baselines.

The tables of the other benchmarks report where each configuration *ends*: its
distance to the optimum once the budget is spent. A data profile reports how it
*gets there*. Each problem is given a ladder of target values, from one any
method reaches early to the global optimum, and the profile of a method is the
fraction of the targets, over every problem and every starting point, that it has
reached after a given number of evaluations. A method solving everything late
and one solving half the problems at once end on different curves that the same
final table would hide.

Two comparisons are drawn from one set of runs. The **variants** of
:mod:`benchmarks.variants` against each other, each changing one thing from the
swept configuration, and then the **best of them** against the baselines of
:mod:`benchmarks.baselines`. The targets are generated once, from the pooled
histories of every run of a dimension, so a curve means the same thing in both.

The budget is that of the main comparison, $500$ equivalent evaluations per
variable, except for EGO, whose surrogate makes a run of that length cost hours:
it is given the $500$ evaluations of :mod:`benchmarks.small_budget` and its
curve ends there.

What `gemseo-benchmark` contributes is the method of comparison, not the runs:
the targets are generated by its :class:`.TargetsGenerator` and the profiles are
those of its :class:`.DataProfile`. Its own :class:`.Benchmarker` is not used,
since it runs the algorithms of a GEMSEO optimization library on a GEMSEO
problem, and neither the method, which is a scenario, nor the baselines run
outside GEMSEO are such algorithms.

The study takes a few hours, EGO accounting for nearly all of it. It spreads the
runs over the processors, keeps each finished run in :data:`.CACHE` so that an
interrupted study resumes where it stopped, and writes the profiles next to the
figures, which ``docs/figures.py`` then draws:

```shell
python -m benchmarks.data_profiles
```
"""

from __future__ import annotations

import json
import logging
import os
from concurrent.futures import ProcessPoolExecutor
from concurrent.futures import as_completed
from dataclasses import asdict
from itertools import product
from pathlib import Path
from statistics import median
from typing import TYPE_CHECKING

from gemseo_benchmark.data_profiles.data_profile import DataProfile
from gemseo_benchmark.data_profiles.target_values import TargetValues
from gemseo_benchmark.data_profiles.targets_generator import TargetsGenerator

from benchmarks import baselines
from benchmarks import variants
from benchmarks.baselines import Result
from benchmarks.problems import PROBLEMS

if TYPE_CHECKING:
    from collections.abc import Iterable
    from collections.abc import Mapping

BUDGET_PER_VARIABLE = 500
"""The budget in equivalent evaluations per variable, that of the main table."""

EGO_BUDGET = 500
"""The budget of EGO, that of :mod:`benchmarks.small_budget`."""

DIMENSIONS = (2, 5)
"""The numbers of design variables, one set of profiles each."""

PROBLEM_NAMES = ("rastrigin", "ackley", "styblinski_tang", "griewank")
"""The problems, those of the main comparison."""

SEEDS = (11, 101, 202, 303, 404)
"""The seeds of the starting points."""

BASELINES = ("multistart", "cmaes", "direct", "egobox")
"""The baselines, compared with the best variant only."""

FLAT_VARIANTS = (
    "swept",
    "margin_100",
    "probes_8",
    "probes_16",
    "ceiling_30",
    "ceiling_10",
    "proposed_density",
    "proposed_density_free",
    "multi_resolution",
    "deep_hierarchy",
)
"""The variants of every dimension."""

VARIANTS = {
    2: FLAT_VARIANTS,
    # Two subdivisions per variable, the default in five, resolve the basins of
    # two problems of four, so the ladder is measured again at the density that
    # resolves Rastrigin; in two variables the default is ten. Sixteen probes
    # at that density is left out: with fifty binaries a master iteration of
    # sixteen probes is so slow that half its runs had not spent their budget
    # after five hours, and the half that had were worse than four probes.
    5: (*FLAT_VARIANTS, "density_10", "density_10_ceiling_10"),
}
"""The variants of each dimension."""

N_TARGETS = 20
"""The number of target values of each problem."""

TOLERANCE = 1e-4
"""The tolerance with which the best target is the global minimum.

It is the gap to the optimum the other benchmarks count as reaching it, relative
to the magnitude of the optimum where that magnitude exceeds one.
"""

OUTPUT = Path(__file__).parent.parent / "docs" / "_static" / "data_profiles.json"
"""The file the profiles are written to, for ``docs/figures.py`` to draw."""

CACHE = Path(__file__).parent / ".data_profiles"
"""The directory keeping the finished runs, one file per dimension.

It is ignored by git: a study resumes from it, and one changing a runner has to
delete it."""


def budget_of(method: str, dimension: int) -> int:
    """Return the budget of a method.

    Args:
        method: The name of the method.
        dimension: The number of design variables.

    Returns:
        The budget in equivalent evaluations.
    """
    return EGO_BUDGET if method == "egobox" else BUDGET_PER_VARIABLE * dimension


def _single_threaded() -> None:
    """Keep a worker process to one thread.

    EGO fits its surrogate over a thread pool of its own, so that one pool per
    process oversubscribes the processors the runs are already spread over.
    """
    for name in ("RAYON_NUM_THREADS", "OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS"):
        os.environ[name] = "1"


def _run(arguments: tuple[str, str, int, int]) -> Result:
    """Run one method on one problem, in a worker process.

    Args:
        arguments: The method, the problem, the dimension and the seed.

    Returns:
        The outcome of the run.
    """
    method, name, dimension, seed = arguments
    budget = budget_of(method, dimension)
    if method in variants.VARIANTS:
        return variants.run(method, PROBLEMS[name], dimension, seed, budget)

    return baselines.run(method, PROBLEMS[name], dimension, seed, budget)


def _key(result: Result) -> tuple[str, str, int, int]:
    """Return what identifies a run.

    Args:
        result: The outcome of the run.

    Returns:
        The method, the problem, the dimension and the seed.
    """
    return result.method, result.problem, result.dimension, result.seed


def _read_cache(path: Path) -> dict[tuple[str, str, int, int], Result]:
    """Return the runs a previous study finished.

    Args:
        path: The file of the cache.

    Returns:
        The outcome of each finished run, by what identifies it.
    """
    if not path.is_file():
        return {}

    results = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        data = json.loads(line)
        data["history"] = tuple(data["history"])
        result = Result(**data)
        results[_key(result)] = result

    return results


def collect(
    dimension: int,
    methods: Iterable[str],
    problem_names: Iterable[str] = PROBLEM_NAMES,
    seeds: Iterable[int] = SEEDS,
    max_workers: int | None = None,
    cache: Path | None = None,
) -> list[Result]:
    """Run every method on every problem and from every starting point.

    Args:
        dimension: The number of design variables.
        methods: The names of the methods, variants and baselines alike.
        problem_names: The names of the problems.
        seeds: The seeds of the starting points.
        max_workers: The number of processes.
            If ``None``, use as many as there are processors.
        cache: The file keeping the finished runs.
            If ``None``, keep none.

    Returns:
        The outcome of every run, each carrying its history.
    """
    tasks = list(product(methods, problem_names, (dimension,), seeds))
    done = _read_cache(cache) if cache else {}
    # The slowest runs first, so that they do not end up alone at the end.
    missing = sorted(
        (task for task in tasks if task not in done),
        key=lambda task: task[0] != "egobox",
    )
    if missing:
        if cache:
            cache.parent.mkdir(parents=True, exist_ok=True)

        with ProcessPoolExecutor(max_workers, initializer=_single_threaded) as executor:
            futures = [executor.submit(_run, task) for task in missing]
            for future in as_completed(futures):
                result = future.result()
                done[_key(result)] = result
                if cache:
                    with cache.open("a", encoding="utf-8") as file:
                        file.write(json.dumps(asdict(result)) + "\n")

    return [done[task] for task in tasks]


def _padded(history: Iterable[float], size: int) -> list[float]:
    """Return a history cut or extended to a size.

    A run ending before its budget has stopped searching, so its best value
    holds until the budget, which is what the profile compares at.

    Args:
        history: The best value after each equivalent evaluation.
        size: The size.

    Returns:
        The history, of that size.
    """
    history = list(history)[:size]
    return history + history[-1:] * (size - len(history))


def compute_targets(
    results: Iterable[Result], n_targets: int = N_TARGETS
) -> dict[str, list[float]]:
    """Generate the target values of each problem from the pooled histories.

    The best target is the global minimum, within :data:`.TOLERANCE`. Where no
    run of any method reaches it, the best target falls back on the best value
    found, which is what a data profile does when the optimum is unknown; the
    profile then compares the methods with each other rather than with the
    optimum, and :func:`.main` says so.

    Args:
        results: The outcome of the runs, of one dimension.
        n_targets: The number of target values of each problem.

    Returns:
        The target values of each problem, from the easiest to the best.
    """
    results = list(results)
    size = max(len(result.history) for result in results)
    generators: dict[str, TargetsGenerator] = {}
    for result in results:
        generator = generators.setdefault(result.problem, TargetsGenerator())
        generator.add_history(_padded(result.history, size))

    targets = {}
    for problem, generator in generators.items():
        optimum = PROBLEMS[problem].optimum(results[0].dimension)
        try:
            values = generator.compute_target_values(
                n_targets,
                best_target_objective=optimum,
                best_target_tolerance=TOLERANCE,
            )
        except RuntimeError:
            values = generator.compute_target_values(
                n_targets, best_target_tolerance=TOLERANCE
            )

        targets[problem] = [float(value) for value in values.performance_measures]

    return targets


def compute_profiles(
    results: Iterable[Result], targets: Mapping[str, list[float]]
) -> dict[str, list[float]]:
    """Compute the data profile of each method, over its own budget.

    Args:
        results: The outcome of the runs, of one dimension.
        targets: The target values of each problem.

    Returns:
        The fraction of the targets reached by each method, after each
        equivalent evaluation of its budget.
    """
    profile = DataProfile({
        problem: TargetValues(values) for problem, values in targets.items()
    })
    for result in results:
        size = budget_of(result.method, result.dimension)
        profile.add_history(
            result.problem, result.method, _padded(result.history, size)
        )

    return profile.compute_data_profiles()


def targeting_the_optimum(
    targets: Mapping[str, list[float]], dimension: int
) -> list[str]:
    """Return the problems whose best target is the global minimum.

    Args:
        targets: The target values of each problem.
        dimension: The number of design variables.

    Returns:
        The names of the problems whose best target is the global minimum, the
        others having fallen back on the best value found.
    """
    names = []
    for name, values in targets.items():
        optimum = PROBLEMS[name].optimum(dimension)
        if values[-1] - optimum <= TOLERANCE * max(1.0, abs(optimum)):
            names.append(name)

    return names


def area(profile: Iterable[float], size: int) -> float:
    """Return the mean fraction of the targets reached over a budget.

    This is the score the variants are ranked by: it rewards reaching targets
    early as well as reaching many, and a profile shorter than the budget holds
    its last value, which is what it would read had the method been given more.

    Args:
        profile: The fraction of the targets reached after each evaluation.
        size: The budget.

    Returns:
        The mean fraction of the targets reached.
    """
    return sum(_padded(profile, size)) / size


def change_points(profile: Iterable[float]) -> list[tuple[int, float]]:
    """Return where a profile changes, which is all it takes to redraw it.

    Args:
        profile: The fraction of the targets reached after each evaluation.

    Returns:
        The evaluation and the fraction at each change, and at the end.
    """
    points = []
    previous = None
    profile = list(profile)
    for index, ratio in enumerate(profile, 1):
        if ratio != previous:
            points.append((index, round(ratio, 4)))
            previous = ratio

    if points[-1][0] != len(profile):
        points.append((len(profile), points[-1][1]))

    return points


def summarize(results: Iterable[Result]) -> dict[str, dict[str, list[float]]]:
    """Return the final gap and cost of each run, the columns of a table.

    Args:
        results: The outcome of the runs, of one dimension.

    Returns:
        The median gap, the median cost and the number of runs reaching the
        optimum, of each method on each problem.
    """
    runs: dict[str, dict[str, list[Result]]] = {}
    for result in results:
        runs.setdefault(result.method, {}).setdefault(result.problem, []).append(result)

    summary: dict[str, dict[str, list[float]]] = {}
    for method, by_problem in runs.items():
        summary[method] = {}
        for problem, outcomes in by_problem.items():
            optimum = PROBLEMS[problem].optimum(outcomes[0].dimension)
            gaps = [outcome.gap(optimum) for outcome in outcomes]
            summary[method][problem] = [
                round(median(gaps), 4),
                median(outcome.cost_adjoint for outcome in outcomes),
                sum(gap <= TOLERANCE * max(1.0, abs(optimum)) for gap in gaps),
            ]

    return summary


def main() -> None:
    """Compute the profiles of every dimension and write them."""
    logging.disable(logging.CRITICAL)
    output = {
        "seeds": len(SEEDS),
        "problems": list(PROBLEM_NAMES),
        "labels": {name: label for name, (label, _) in variants.VARIANTS.items()},
        "dimensions": {},
    }
    for dimension in DIMENSIONS:
        budget = BUDGET_PER_VARIABLE * dimension
        methods = (*VARIANTS[dimension], *BASELINES)
        results = collect(dimension, methods, cache=CACHE / f"{dimension}.jsonl")
        targets = compute_targets(results)
        profiles = compute_profiles(results, targets)
        ranking = sorted(
            VARIANTS[dimension],
            key=lambda name: area(profiles[name], budget),
            reverse=True,
        )
        optimal = targeting_the_optimum(targets, dimension)
        output["dimensions"][str(dimension)] = {
            "budget": budget,
            "best_target_is_the_optimum": optimal,
            "targets": targets,
            "ranking": ranking,
            "areas": {
                name: round(area(profile, budget), 4)
                for name, profile in profiles.items()
            },
            "summary": summarize(results),
            "profiles": {
                name: change_points(profile) for name, profile in profiles.items()
            },
        }
        print(f"{dimension} variables, best target the optimum on {optimal}")  # noqa: T201
        checkpoints = [budget // 10, budget // 4, budget // 2, budget]
        print(f"{'':>22} {'area':>5} " + " ".join(f"{c:>5}" for c in checkpoints))  # noqa: T201
        for name in (*ranking, *BASELINES):
            profile = _padded(profiles[name], budget)
            cells = " ".join(f"{profile[c - 1]:>5.0%}" for c in checkpoints)
            print(f"{name:>22} {area(profile, budget):>5.2f} {cells}")  # noqa: T201

    OUTPUT.write_text(json.dumps(output, indent=2) + "\n", encoding="utf-8")
    logging.disable(logging.NOTSET)


if __name__ == "__main__":
    main()
